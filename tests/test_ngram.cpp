// prev[i*2+0] = i-2 位的 token（无则 -1，越靠前越旧）；prev[i*2+1] = i-1 位。
std::vector<std::int32_t> build_prev(const std::vector<std::int32_t>& seq) {
    std::vector<std::int32_t> prev(seq.size() * 2);
    for (std::size_t i = 0; i < seq.size(); ++i) {
        prev[i * 2] = i >= 2 ? seq[i - 2] : kTokenNull;
        prev[i * 2 + 1] = i >= 1 ? seq[i - 1] : kTokenNull;
    }
    return prev;
}

struct Case {
    std::vector<std::int32_t> tokens;
    std::vector<std::uint32_t> rows;   // 每 token 16 个，token-major
};

void check(const Case& c) {
    const std::vector<std::int32_t> prev = build_prev(c.tokens);
    std::vector<std::uint32_t> got(c.tokens.size() * kPleNHeads);
    ngram_rows(c.tokens.data(), prev.data(), static_cast<int>(c.tokens.size()),
               ple_artifact_consts(), got.data());
    CHECK(got.size() == c.rows.size());
    for (std::size_t k = 0; k < got.size(); ++k) {
        if (got[k] != c.rows[k]) {
            std::printf("FAIL at token %zu head %zu: got %u want %u\n",
                        k / kPleNHeads, k % kPleNHeads, got[k], c.rows[k]);
            CHECK(false);
        }
    }
}

