void test_rows_stay_inside_their_head_region() {
    // 结构性不变量（G-04 的结论就建立在这上面）：第 h 个头的行必须落在该头独占的连续区间里，
    // 16 个区间互不相邻。任何「读错头」的实现都会越界。
    const PleConsts& c = ple_artifact_consts();
    const std::vector<std::int32_t> seq{11, 22, 33, 44, 55, 66, 77, 88};
    const std::vector<std::int32_t> prev = build_prev(seq);
    std::vector<std::uint32_t> rows(seq.size() * kPleNHeads);
    ngram_rows(seq.data(), prev.data(), static_cast<int>(seq.size()), c, rows.data());

    for (std::size_t i = 0; i < seq.size(); ++i) {
        for (int h = 0; h < kPleNHeads; ++h) {
            const std::uint32_t r = rows[i * kPleNHeads + h];
            CHECK(r >= c.offset[h] && r < c.offset[h] + c.vocab[h]);
        }
        // 16 个头给出的行两两不同（区间互不相邻的直接推论）
        for (int a = 0; a < kPleNHeads; ++a) {
            for (int b = a + 1; b < kPleNHeads; ++b) {
                CHECK(rows[i * kPleNHeads + a] != rows[i * kPleNHeads + b]);
            }
        }
    }
}

void test_missing_predecessor_is_eos_cut() {
    // 序列开头没有前序：第一位的前序必须按 EOS 参与哈希，等价于把前序替换成 EOS。
    const PleConsts& c = ple_artifact_consts();
    const std::vector<std::int32_t> a{100, 101};
    const std::vector<std::int32_t> prev_a{ -1, -1, kTokenNull, -1 };
    std::vector<std::uint32_t> rows_a(2 * kPleNHeads);
    ngram_rows(a.data(), prev_a.data(), 2, c, rows_a.data());

    // 显式写 EOS 作前序，结果应一致
    const std::vector<std::int32_t> prev_eos{ -1, -1, kPleEosTokenId, -1 };
    std::vector<std::uint32_t> rows_eos(2 * kPleNHeads);
    ngram_rows(a.data(), prev_eos.data(), 2, c, rows_eos.data());

    for (int k = 0; k < 2 * kPleNHeads; ++k) CHECK(rows_a[k] == rows_eos[k]);
}

